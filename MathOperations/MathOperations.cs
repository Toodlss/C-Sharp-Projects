// Creates a class named MathOperations that will contain our math methods.
public class MathOperations
{
    // Creates a method named AddTen that accepts one integer and returns an integer.
    public int AddTen(int number)
    {
        // Adds 10 to the number provided by the user and returns the result.
        return number + 10;
    }

    // Creates a method named MultiplyByTwo that accepts one integer and returns an integer.
    public int MultiplyByTwo(int number)
    {
        // Multiplies the provided number by 2 and returns the result.
        return number * 2;
    }

    // Creates a method named SubtractFive that accepts one integer and returns an integer.
    public int SubtractFive(int number)
    {
        // Subtracts 5 from the provided number and returns the result.
        return number - 5;
    }
}